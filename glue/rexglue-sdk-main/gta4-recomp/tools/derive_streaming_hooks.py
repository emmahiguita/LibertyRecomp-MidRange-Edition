def fixture_sources(bodies: dict[str, str], destination: Path) -> None:
    """Extract real baseline code and register save/restore helpers for differential tests."""
    required = set()
    for body in bodies.values():
        required.update(re.findall(r'\b(__\w+)\(ctx, base\);', body))
    helpers: dict[str, str] = {}
    for path in sorted(GENERATED.glob('gta4_recomp.*.cpp')):
        text = path.read_text()
        for name in required - helpers.keys():
            if f'DEFINE_REX_FUNC({name}) {{' in text:
                helpers[name] = extract(text, name)
    missing = required - helpers.keys()
    if missing:
        raise ValueError(f'Missing compiled register helpers: {sorted(missing)}')
    content = '// Test baseline extracted from compiled sources; no behavioural reconstruction.\n'
    for name in sorted(helpers):
        content += replace_once(helpers[name], f'DEFINE_REX_FUNC({name}) {{',
                                f'extern "C" void {name}(PPCContext& ctx, uint8_t* base) {{') + '\n'
    for name, body in bodies.items():
        body = replace_once(body, f'DEFINE_REX_FUNC({name}) {{',
                            f'extern "C" void __imp__{name}(PPCContext& ctx, uint8_t* base) {{')
        # A baseline recursive call must stay entirely on the baseline path.
        body = body.replace(f'\t{name}(ctx, base);', f'\t__imp__{name}(ctx, base);')
        content += body + '\n'
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'streaming_original_fixture.inc').write_text(content)


def verify_host_shutdown_contract() -> None:
    """Check production ordering; runtime queue tests exercise the drain primitive."""
    source = (ROOT.parent/'src/system/kernel_state.cpp').read_text()
    shutdown = source.split('void KernelState::TerminateTitle() {', 1)[1].split('\n}\n', 1)[0]
    markers = ('dispatch_accepting_ = false;', 'host_io_accepting_ = false;',
               'WaitForHostTasks();', 'terminating_title_.store(true, std::memory_order_release);',
               'SignalAllWaitableObjects();')
    positions = [shutdown.index(marker) for marker in markers]
    if positions != sorted(positions):
        raise ValueError('Host admission must stop and drain before cooperative guest exit')
    restart = source.split('void KernelState::StartHostIoWorkers() {', 1)[1].split('\n}\n', 1)[0]
    retained = restart.split('if (host_io_queue_) {', 1)[1].split('}', 1)[0]
    if 'host_io_accepting_ = true;' not in retained:
        raise ValueError('Retained I/O workers must reopen admission for the new title')
    print('PASS: host admission fence, drain-before-exit and worker reuse contract')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    parser.add_argument('--fixture-output', type=Path)
    args = parser.parse_args()
    verify_host_shutdown_contract()
    bodies = originals()
    derived = derive(bodies)
    if args.write:
        if not OUTPUT.exists() or OUTPUT.read_text() != derived:
            OUTPUT.write_text(derived)
    elif not OUTPUT.exists() or OUTPUT.read_text() != derived:
        raise ValueError(f'{OUTPUT}: does not match pinned derivation; run --write after review')
    if args.fixture_output:
        fixture_sources(bodies, args.fixture_output)
    print('PASS: pinned compiled sources and exact streaming substitutions verified')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError) as error:
        print(f'FAIL: {error}', file=sys.stderr)
        sys.exit(1)
