#!/usr/bin/env python3
"""Derive narrow streaming hooks from pinned, compiled PPC translation units."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / 'generated'
OUTPUT = ROOT / 'src/gta4_streaming_guest.inc'
SOURCES = {
    'sub_821D8848': (5, 'b186dcb19e0df64d253808b55e10469e58b30d0c2a73c6053b7fde5b7d97387e'),
    'sub_825132D0': (33, '1b41bef76f16ae62b8ec60235bfc46cfbd87f46d225509ecab533676884fc9a9'),
}
HEADER = '''// Derived by tools/derive_streaming_hooks.py --write.
// Full reviewed generated PPC; narrowly scoped preload and ranking substitutions.
// No generated source is modified. Do not edit this file manually.

'''


def extract(text: str, name: str) -> str:
    marker = f'DEFINE_REX_FUNC({name}) {{'
    if text.count(marker) != 1:
        raise ValueError(f'{name}: expected one compiled definition')
    start = text.index(marker)
    end = text.find('\nDEFINE_REX_FUNC(', start + len(marker))
    return text[start:end if end >= 0 else len(text)].rstrip() + '\n'


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError(f'Expected one substitution site: {old!r}; found {text.count(old)}')
    return text.replace(old, new, 1)


def originals() -> dict[str, str]:
    result = {}
    for name, (unit, expected_hash) in SOURCES.items():
        body = extract((GENERATED / f'gta4_recomp.{unit}.cpp').read_text(), name)
        actual = hashlib.sha256(body.encode()).hexdigest()
        if actual != expected_hash:
            raise ValueError(f'{name}: compiled source changed ({actual}); review before updating the pin')
        result[name] = body
    return result


# Retain the interface used by the existing differential-test runner.
SPECS = tuple((name, unit, digest) for name, (unit, digest) in SOURCES.items())

def original(name: str, unit: int, expected_hash: str) -> str:
    body = extract((GENERATED / f'gta4_recomp.{unit}.cpp').read_text(), name)
    actual = hashlib.sha256(body.encode()).hexdigest()
    if actual != expected_hash:
        raise ValueError(f'{name}: source changed ({actual}); review required')
    return body


